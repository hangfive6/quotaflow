CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    total_stock INT NOT NULL,
    available_stock INT NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_product_stock CHECK (total_stock >= 0 AND available_stock >= 0 AND available_stock <= total_stock)
);

CREATE TABLE reservations (
    id UUID PRIMARY KEY,
    product_id BIGINT NOT NULL,
    customer_id VARCHAR(80) NOT NULL,
    quantity INT NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6),
    CONSTRAINT uk_reservation_idempotency UNIQUE (idempotency_key),
    CONSTRAINT fk_reservation_product FOREIGN KEY (product_id) REFERENCES products(id)
);
CREATE INDEX idx_reservation_expiry ON reservations(status, expires_at);

CREATE TABLE outbox_events (
    id UUID PRIMARY KEY,
    event_type VARCHAR(60) NOT NULL,
    aggregate_type VARCHAR(60) NOT NULL,
    aggregate_id VARCHAR(80) NOT NULL,
    payload TEXT NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    published_at TIMESTAMP(6)
);
CREATE INDEX idx_outbox_pending ON outbox_events(published_at, created_at);

